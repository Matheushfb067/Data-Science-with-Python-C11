'''
8. Crie um programa que leia dois números calcule e mostre na tela:
• Adição
• Subtração
• Multiplicação
• Divisão
• Resto da divisão
• Potência (primeiro número elevado ao segundo
'''

num1 = float(input('Entre com o primeiro numero: '))
num2 = float(input('Entre com o segundo numero: '))

print(f'A Adicao entre {num1} e {num2} é: {num1 + num2}')
print(f'A Subtração entre {num1} e {num2} é: {num1 - num2}')
print(f'A Multiplicação entre {num1} e {num2} é: {num1 * num2}')
print(f'A Divisão entre {num1} e {num2} é: {num1 / num2}')
print(f'O Resto da divisão entre {num1} e {num2} é: {num1 % num2}')
print(f'A Potencia entre {num1} e {num2} é: {num1 ** num2}')