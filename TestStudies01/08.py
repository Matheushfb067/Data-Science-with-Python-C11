'''
8. Crie um programa que leia dois números calcule e mostre na tela:
• Adição
• Subtração
• Multiplicação
• Divisão
• Resto da divisão
• Potência (primeiro número elevado ao segundo)
'''

num1 = int(input("Entre com o primeiro numero: "))
num2 = int(input("Entre com o segundo numero: "))

print(f"soma: {num1 + num2}")
print(f"subtraçao: {num1 - num2}")
print(f"multiplicação: {num1 * num2}")
print(f"divisão: {num1 / num2}")
print(f"resto da divisão: {num1 % num2}")
print(f"potencia: {num1 ** num2}")